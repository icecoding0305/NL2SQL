-- 贷款借据信息表 DWD_AR_LOAN_INFO(Hive DDL 转 MySQL)
-- 在 nl2sql 库手动执行:
--   mysql -h mysql5.sqlpub.com -P 3310 -u fbrisk -p nl2sql < sql/mysql_贷款借据信息表.sql
CREATE TABLE IF NOT EXISTS `dwd_ar_loan_info` (
  `LOAN_NO` VARCHAR(100) NOT NULL COMMENT '借据编码',
  `CONT_NO` VARCHAR(100) COMMENT '合同编码',
  `CUST_ID` VARCHAR(100) COMMENT '客户号',
  `PRD_CODE` VARCHAR(100) COMMENT '产品编码',
  `NAME` VARCHAR(100) COMMENT '客户姓名',
  `IDTYPE` VARCHAR(100) COMMENT '证件类型',
  `IDNUM` VARCHAR(100) COMMENT '证件号码',
  `START_DATE` DATE COMMENT '借款开始日期',
  `END_DATE` DATE COMMENT '借款结束日期',
  `LOAN_STATUS` VARCHAR(100) COMMENT '贷款状态',
  `END_SIGN` INT COMMENT '停息标识',
  `CANCEL_REASON` VARCHAR(100) COMMENT '贷款撤销原因',
  `PAYOFF_DATE` DATE COMMENT '结清日期',
  `TOTAL_TERMS` INT COMMENT '贷款期数',
  `GRACE_DAY` INT COMMENT '宽限天数',
  `IS_DEBT_TR` INT COMMENT '是否债转',
  `IS_DEBT_TR_DATE` DATE COMMENT '债转日期',
  `RATE_TYPE` VARCHAR(100) COMMENT '利率类型',
  `YEAR_RATE` DECIMAL(24,6) COMMENT '年利率',
  `DAY_RATE` DECIMAL(24,6) COMMENT '日利率',
  `PNLT_RATE` DECIMAL(24,6) COMMENT '罚息利率',
  `YEAR_RATE_PROFIT` DECIMAL(24,6) COMMENT '我行利率',
  `CAPITAL_RATIO` DECIMAL(24,6) COMMENT '出资比例',
  `LOAN_AMT` DECIMAL(24,6) COMMENT '贷款金额',
  `PRIN_BAL` DECIMAL(24,6) COMMENT '贷款本金余额',
  `NORMAL_BAL` DECIMAL(24,6) COMMENT '正常本金余额',
  `OVD_BAL` DECIMAL(24,6) COMMENT '逾期本金余额',
  `INPUT_DATE` DATE COMMENT '录入日期',
  `INPUT_TIME` DATE COMMENT '录入时间',
  `LAST_UPDATE_DATE` DATE COMMENT '最后更新日期',
  `LAST_UPDATE_TIME` DATE COMMENT '最后更新时间',
  `DATA_DATE` VARCHAR(100) COMMENT '数据日期字符串类型',
  `DATA_DATE_NUM` VARCHAR(100) COMMENT '数据日期数字类型',
  `PLATFORM_CODE` VARCHAR(100) COMMENT '平台代码',
  PRIMARY KEY (`LOAN_NO`),
  INDEX `idx_loan_cust` (`CUST_ID`),
  INDEX `idx_loan_cont` (`CONT_NO`),
  CONSTRAINT `fk_loan_cust` FOREIGN KEY (`CUST_ID`) REFERENCES `dwd_ip_indv_cust_info` (`CUST_ID`)
    ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='协议-贷款借据信息-贷款借据信息表';